def rotulo(texto, x, y, alt=3.0):
    """Texto em polilinhas. Sem fonte instalada, sem
    dependencia, e legivel depois de cortado."""
    larg = alt * 0.7
    esp = alt * 0.28
    linhas = []
    cx = x
    for ch in str(texto).upper():
        for tr in _G.get(ch, []):
            linhas.append([(cx + px * larg, y + py * alt) for px, py in tr])
        cx += larg + esp
    return linhas


def largura_texto(texto, alt=3.0):
    return len(str(texto)) * (alt * 0.7 + alt * 0.28)

